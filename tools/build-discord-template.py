#!/usr/bin/env python3
"""Assemble the offline Discord template from maintained CSS and pinned dependencies."""

import argparse
import base64
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
TEMPLATE = ASSETS / "templates/discord"


def data_url(path, mime):
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def assemble():
    source = (TEMPLATE / "nythera.css").read_text()
    header, source = source.split("*/", 1)
    parts = [header + "*/\n/* Generated by tools/build-discord-template.py; edit nythera.css instead. */\n"]
    for name in ("midnight", "system24"):
        css = (TEMPLATE / "vendor" / f"{name}.css").read_text()
        # Nythera overrides both font families with the client's fonts. System24's
        # ASCII font remains bundled for its headings. No runtime CSS/font fetches.
        css = re.sub(r"^@import[^\n]*\n", "", css, flags=re.MULTILINE)
        replacements = {
            "https://refact0r.github.io/system24/assets/asciid.woff": data_url(TEMPLATE / "vendor/asciid.woff", "font/woff"),
            "https://raw.githubusercontent.com/refact0r/system24/refs/heads/main/assets/cats.gif": data_url(TEMPLATE / "vendor/cats.gif", "image/gif"),
            # System24 overrides this unused Midnight icon; don't ship its network dependency.
            "https://refact0r.github.io/midnight-discord/assets/Font_Awesome_5_solid_moon.svg": "",
        }
        for url, replacement in replacements.items():
            css = css.replace(url, replacement)
        licence = (TEMPLATE / "vendor" / f"{name}.LICENSE").read_text()
        parts.append(f"\n/* Bundled {name}\n{licence}*/\n" + css)
    source = re.sub(r"^@import[^\n]*\n", "", source, flags=re.MULTILINE)
    for name in ("nythera-logo-flat.svg", "nythera-header-accent.svg"):
        source = source.replace(
            f"https://raw.githubusercontent.com/Kangy1103/Nythera/dev/assets/{name}",
            data_url(ASSETS / name, "image/svg+xml"),
        )
    parts.append("\n/* Nythera overrides */\n" + source)
    result = "".join(parts)
    if re.search(r"@import\b|url\(\s*['\"]?(?:https?:)?//", result):
        raise ValueError("Unbundled dependency in Discord template")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the shipped template matches its sources")
    args = parser.parse_args()
    output = TEMPLATE / "nythera.theme.css"
    rendered = assemble()
    if args.check:
        if not output.exists() or output.read_text() != rendered:
            parser.exit(1, "Discord template is stale; run python3 tools/build-discord-template.py\n")
    else:
        output.write_text(rendered)
